/**
 * Load all CMA tab data for a listing.
 * Agents see own listings. Admins/brokers see all (RLS enforced).
 */
export async function loadCMAPageData(listingId: string): Promise<CMAPageData> {
  const supabase = await createClient()

  const [cmaRes, upgradesRes, agreementRes] = await Promise.all([
    supabase
      .from("cma_reports")
      .select("*")
      .eq("listing_id", listingId)
      .order("created_at", { ascending: false })
      .limit(1)
      .maybeSingle(),
    supabase
      .from("property_upgrades")
      .select("*")
      .eq("listing_id", listingId)
      .order("created_at", { ascending: false }),
    supabase
      .from("listing_agreements")
      .select(
        "id, listing_commission_rate, buyer_commission_rate, total_commission_rate, commission_is_flat_fee, commission_flat_amount, seller_transaction_fee, has_commission_adjustment, adjustment_type, adjustment_value, adjustment_notes, esign_status, fully_executed_at"
      )
      .eq("listing_id", listingId)
      .order("created_at", { ascending: false })
      .limit(1)
      .maybeSingle(),
  ])

  const cmaRow = cmaRes.data
  let comparables: CMAComparable[] = []
  let compScores: Record<string, AICompScore> = {}
  let riskFlags: CompRiskFlag[] = []

  if (cmaRow) {
    const [compsRes, scoresRes, flagsRes] = await Promise.all([
      supabase
        .from("cma_comparables")
        .select("*")
        .eq("cma_id", cmaRow.id)
        .order("similarity_score", { ascending: false }),
      supabase
        .from("ai_comp_scores")
        .select("*")
        .eq("cma_id", cmaRow.id),
      supabase
        .from("comp_risk_flags")
        .select("*")
        .eq("cma_id", cmaRow.id)
        .eq("is_resolved", false),
    ])

    comparables = compsRes.data ?? []
    riskFlags = flagsRes.data ?? []

    if (scoresRes.data) {
      for (const score of scoresRes.data) {
        compScores[score.comparable_id] = score
      }
    }
  }

  // Determine if auto-generated (no human actor — lifecycle triggered)
  const autoGenerated = cmaRow
    ? cmaRow.status === "auto_generated"
    : false

  const cma: CMAReport | null = cmaRow
    ? {
        ...cmaRow,
        hasAIScores: Object.keys(compScores).length > 0,
        autoGenerated,
      }
    : null

  return {
    cma,
    comparables,
    compScores,
    riskFlags,
    propertyUpgrades: upgradesRes.data ?? [],
    agreement: agreementRes.data ?? null,
  }
}


/**
 * Trigger AI comp scoring for the latest CMA on a listing.
 * Delegates to scoreAllComps() which handles all DB writes + kernel events.
 */
export async function triggerAICompScoring(
  cmaId: string,
  listingId: string
): Promise<{ success: boolean; scored?: number; error?: string }> {
  const supabase = await createClient()

  const { data: user } = await supabase.auth.getUser()
  if (!user.user) return { success: false, error: "Unauthenticated" }

  const { data: profile } = await supabase
    .from("users")
    .select("brokerage_id")
    .eq("id", user.user.id)
    .single()

  if (!profile?.brokerage_id) return { success: false, error: "No brokerage found" }

  const result = await scoreAllComps(
    cmaId,
    listingId,
    profile.brokerage_id,
    user.user.id
  )

  return { success: result.success, scored: result.scored, error: result.error }
}


#!/usr/bin/env tsx
/**
 * GENERATOR — scripts/unique-indexes.ts (the cache scripts/upsert-conflict-target-guard.ts judges against).
 *
 *   npx tsx scripts/generate-unique-indexes.ts --sql            # prints the query for the tables the code upserts into
 *   npx tsx scripts/generate-unique-indexes.ts < live.json      # writes the cache from the query's JSON result
 *
 * The query returns one row per table: { tbl, sets } where `sets` lists, for each unique index that is NOT partial and NOT an
 * expression index, its columns sorted and comma-joined. A table with no such index returns an empty list (kept — "none" is a
 * fact). The live database is the source of truth (CLAUDE.md §3): never hand-edit the cache.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { censusUpserts } from "./upsert-conflict-target-guard"

const ROOT = process.cwd()
const tables = [...new Set(censusUpserts(ROOT).sites.map((s) => s.table).filter((t): t is string => !!t && /^[a-z0-9_]+$/.test(t)))].sort()

if (process.argv.includes("--sql")) {
  console.log(`select c.relname as tbl,
  coalesce((select json_agg(s.cols order by s.cols) from (
    select (select string_agg(a.attname, ',' order by a.attname) from unnest(i.indkey) k join pg_attribute a on a.attrelid = c.oid and a.attnum = k) as cols
    from pg_index i where i.indrelid = c.oid and i.indisunique and i.indpred is null and i.indexprs is null) s), '[]'::json) as sets
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind in ('r','p') and c.relname in (${tables.map((t) => `'${t}'`).join(",")})
order by 1;`)
  process.exit(0)
}

const rows = JSON.parse(readFileSync(0, "utf8")) as Array<{ tbl: string; sets: string[] | string }>
const cache: Record<string, string[]> = {}
for (const r of rows) cache[r.tbl] = [...new Set((typeof r.sets === "string" ? JSON.parse(r.sets) : r.sets) as string[])].sort()
const missing = tables.filter((t) => !(t in cache))
const body = `// GENERATED by scripts/generate-unique-indexes.ts from the live database — never hand-edit (CLAUDE.md §3).
// For each table the code upserts into: the column sets of its unique indexes that are NOT partial and NOT expression indexes
// (the only ones an ON CONFLICT (cols) with no predicate can use). Columns sorted, comma-joined.
export const UNIQUE_INDEX_SNAPSHOT_AT = ${JSON.stringify(new Date().toISOString().slice(0, 10))}
export const UNIQUE_INDEX_TABLES_READ = ${rows.length}
export const INFERABLE_UNIQUE_SETS: Readonly<Record<string, readonly string[]>> = Object.freeze({
${Object.keys(cache).sort().map((t) => `  ${t}: ${JSON.stringify(cache[t])},`).join("\n")}
})
`
writeFileSync(join(ROOT, "scripts/unique-indexes.ts"), body)
console.log(`✅ unique indexes: ${rows.length} tables, ${Object.values(cache).reduce((n, s) => n + s.length, 0)} inferable unique column sets (read via stdin)${missing.length ? ` · NOT RETURNED (table absent live?): ${missing.join(", ")}` : ""}`)

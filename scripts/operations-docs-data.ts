/**
 * scripts/operations-docs-data.ts   (wave 143, lane 143H)
 * ─────────────────────────────────────────────────────────────────────────────
 * THE CURATED HALF OF docs/operations/ENVIRONMENT-INVENTORY.md.
 *
 * Everything that CAN be derived is derived by scripts/operations-docs-guard.ts (the census of reads, the
 * documented sources, the launch tier, the tenancy model, the webhook door that holds a secret). What cannot be
 * derived — WHAT A NAME IS FOR, WHICH SYSTEM OWNS IT, WHERE A HUMAN OBTAINS IT, HOW IT IS VERIFIED — is a human
 * judgement and lives here, once, keyed by the exact name. The guard refuses (a) a name the code or the example file
 * carries that has no row here (an unclassified name) and (b) a row here that names nothing the code, the example file
 * or a registry carries (a phantom row), so this file cannot rot silently in either direction.
 *
 * NO VALUES. This file holds names, purposes and public documentation pointers. It never holds a credential, and the
 * guard refuses any secret-shaped literal in the docs it feeds.
 *
 * Requirement vocabulary (one spelling, CLAUDE.md §6):
 *   REQUIRED      the platform cannot honestly onboard a paying tenant without it (launch-blocking), or a gate fails closed.
 *   DEGRADED      launch is possible; the capability lane runs in its honest absent/fallback mode without it.
 *   OPTIONAL      a nice-to-have, an override, or a feature flag with a code default.
 *   PROVIDED      set by Vercel / Node at runtime or build; nothing to type in.
 *   DEV-ONLY      must be UNSET in Production; the code hard-gates it off there (the guard proves the gate).
 *   RETIRED       the capability it fed was removed; listed so an operator who finds it knows it is inert.
 *   ALIAS         a deprecated second spelling of a survivor (CLAUDE.md §6) — set the survivor.
 *   CI/TOOLING    read by workflows, scripts or seed tooling, never by the deployed app.
 *   UNUSED        declared by a registry or a UI table, but no code path obtains it today.
 *   UNIMPLEMENTED the code reads it but the lane honestly refuses (no third-party API is offered).
 */

export type Req = "REQUIRED" | "DEGRADED" | "OPTIONAL" | "PROVIDED" | "DEV-ONLY" | "RETIRED" | "ALIAS" | "CI/TOOLING" | "UNUSED" | "UNIMPLEMENTED"

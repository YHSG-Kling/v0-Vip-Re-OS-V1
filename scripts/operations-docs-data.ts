export type SysKey = keyof typeof SYSTEMS

export interface Meta {
  sys: SysKey
  kind: Kind
  purpose: string
  req?: Req
  /** For ALIAS: the survivor spelling. */
  alias?: string
  /** For a name with no direct `process.env.X` read: the declaration/consumer that proves it is obtained (computed key). */
  via?: string
}

export const ENV_META: Record<string, Meta> = {}

type Row = [name: string, purpose: string, req?: Req, extra?: { alias?: string; via?: string }]
function add(sys: SysKey, kind: Kind, rows: Row[]): void {
  for (const [name, purpose, req, extra] of rows) {
    if (ENV_META[name]) throw new Error(`operations-docs-data: duplicate row ${name}`)
    ENV_META[name] = { sys, kind, purpose, ...(req ? { req } : {}), ...(extra ?? {}) }
  }
}

